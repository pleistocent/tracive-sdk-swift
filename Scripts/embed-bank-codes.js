#!/usr/bin/env node
// Embeds the vendored bank-code table in the SDK as a Swift string constant.
//
// The SDK target ships no resource bundle, so the table travels as source. After re-vendoring
// Tests/TraciveSDKTests/Fixtures/bank-codes.json, run `node Scripts/embed-bank-codes.js`.
// BankCodeTests fails when the constant and the vendored file differ by a single byte.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const SOURCE = 'Tests/TraciveSDKTests/Fixtures/bank-codes.json';
const TARGET = 'Sources/TraciveSDK/Query/BankCodesJSON.swift';

const json = readFileSync(join(ROOT, SOURCE), 'utf8');

// A `#"""` raw string ends at `"""#` and interpolates at `\#(`, so neither may occur in the data.
if (json.includes('"""#') || json.includes('\\#')) {
  console.error(`embed-bank-codes: ${SOURCE} contains a sequence that would end the Swift literal.`);
  process.exit(1);
}
JSON.parse(json);

const swift = [
  `// Generated by Scripts/embed-bank-codes.js from ${SOURCE}.`,
  '// Do not edit: re-vendor that file and re-run the script. BankCodeTests fails if the two differ.',
  '',
  'extension BankCodes {',
  '  static let json = #"""',
  json,
  '"""#',
  '}',
  '',
].join('\n');

writeFileSync(join(ROOT, TARGET), swift);
console.log(`embed-bank-codes: wrote ${TARGET} (${Buffer.byteLength(json)} bytes of JSON)`);
